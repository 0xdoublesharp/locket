use std::cell::RefCell;

use objc2::{AnyThread, ClassType, DefinedClass, define_class};
use objc2_foundation::NSObject;

use super::*;

const TEST_PASTEBOARD: Pasteboard = Pasteboard(c"LocketTestPasteboard");

thread_local! {
    static ACTIVE_BOARD: RefCell<Option<Retained<TestPasteboard>>> = const { RefCell::new(None) };
}

#[derive(Default)]
struct BoardState {
    generation: isize,
    options: usize,
    writes: Vec<(String, Vec<u8>)>,
    reject_type: Option<&'static str>,
    replace_on_text: bool,
}

define_class!(
    // SAFETY: NSObject permits subclassing. All fake state belongs to the
    // instance and the selectors below match the pasteboard ABI.
    #[unsafe(super = NSObject)]
    #[name = "LocketTestPasteboard"]
    #[ivars = RefCell<BoardState>]
    struct TestPasteboard;

    impl TestPasteboard {
        #[unsafe(method_id(generalPasteboard))]
        fn general() -> Option<Retained<Self>> {
            ACTIVE_BOARD.with_borrow(Clone::clone)
        }

        #[unsafe(method(prepareForNewContentsWithOptions:))]
        fn prepare(&self, options: usize) -> isize {
            let mut state = self.ivars().borrow_mut();
            state.generation += 1;
            state.options = options;
            state.writes.clear();
            state.generation
        }

        #[unsafe(method(setData:forType:))]
        fn set(&self, data: &NSData, kind: &NSString) -> Bool {
            let mut state = self.ivars().borrow_mut();
            let kind = kind.to_string();
            if state.reject_type == Some(kind.as_str()) {
                return Bool::NO;
            }
            if state.replace_on_text && kind == TEXT_TYPE {
                state.generation += 1;
            }
            state.writes.push((kind, data.to_vec()));
            Bool::YES
        }

        #[unsafe(method(changeCount))]
        fn count(&self) -> isize {
            self.ivars().borrow().generation
        }

        #[unsafe(method(clearContents))]
        fn clear(&self) -> isize {
            let mut state = self.ivars().borrow_mut();
            state.generation += 1;
            state.writes.clear();
            state.generation
        }
    }
);

fn fake_board() -> Retained<TestPasteboard> {
    let allocated = TestPasteboard::alloc().set_ivars(RefCell::default());
    // SAFETY: NSObject's init is valid for this initialized subclass allocation.
    let board: Retained<TestPasteboard> = unsafe { msg_send![super(allocated), init] };
    ACTIVE_BOARD.with_borrow_mut(|active| *active = Some(board.clone()));
    board
}

#[test]
fn concealed_write_publishes_markers_before_utf8_and_expires_only_its_generation()
-> Result<(), PlatformError> {
    let board = fake_board();
    let concealed = TEST_PASTEBOARD.write_concealed_secret("secret 🗝")?;
    {
        let state = board.ivars().borrow();
        assert_eq!(state.options, CURRENT_HOST_ONLY);
        assert_eq!(
            state.writes,
            [
                ("org.nspasteboard.ConcealedType".into(), vec![]),
                ("org.nspasteboard.TransientType".into(), vec![]),
                ("org.nspasteboard.AutoGeneratedType".into(), vec![]),
                ("public.utf8-plain-text".into(), "secret 🗝".as_bytes().to_vec()),
            ]
        );
    }

    TEST_PASTEBOARD.write_plain_text("replacement")?;
    let replacement = change_count(&board);
    assert_ne!(replacement, concealed);
    assert!(!TEST_PASTEBOARD.clear_if_unchanged(concealed)?);
    {
        let state = board.ivars().borrow();
        assert_eq!(state.options, 0);
        assert_eq!(state.writes, [(TEXT_TYPE.into(), b"replacement".to_vec())]);
    }
    assert!(TEST_PASTEBOARD.clear_if_unchanged(replacement)?);
    assert_eq!(board.ivars().borrow().writes.as_slice(), &[] as &[(String, Vec<u8>)]);
    assert!(!TEST_PASTEBOARD.clear_if_unchanged(replacement)?);
    Ok(())
}

#[test]
fn rejected_marker_never_publishes_plaintext_and_ownership_changes_fail_closed() {
    let board = fake_board();
    board.ivars().borrow_mut().reject_type = Some(SECRET_MARKERS[1]);
    assert!(matches!(
        TEST_PASTEBOARD.write_concealed_secret("secret"),
        Err(PlatformError::PasteboardUnavailable)
    ));
    assert_eq!(board.ivars().borrow().writes, [(SECRET_MARKERS[0].into(), vec![])]);

    board.ivars().borrow_mut().reject_type = Some(TEXT_TYPE);
    assert!(matches!(
        TEST_PASTEBOARD.write_plain_text("secret"),
        Err(PlatformError::PasteboardUnavailable)
    ));
    assert_eq!(board.ivars().borrow().writes.as_slice(), &[] as &[(String, Vec<u8>)]);

    {
        let mut state = board.ivars().borrow_mut();
        state.reject_type = None;
        state.replace_on_text = true;
    }
    assert!(matches!(
        TEST_PASTEBOARD.write_concealed_secret("secret"),
        Err(PlatformError::PasteboardUnavailable)
    ));
}

#[test]
fn missing_class_and_missing_board_both_fail_closed() {
    let _registered = TestPasteboard::class();
    ACTIVE_BOARD.with_borrow_mut(|active| *active = None);
    for board in [TEST_PASTEBOARD, Pasteboard(c"LocketUnregisteredTestPasteboard")] {
        assert!(matches!(
            board.write_concealed_secret("fixture"),
            Err(PlatformError::PasteboardUnavailable)
        ));
    }
}
